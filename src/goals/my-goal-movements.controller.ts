import {
  Body,
  Controller,
  Get,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Post,
  Query,
  Res,
} from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiConflictResponse,
  ApiCreatedResponse,
  ApiHeader,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import type { Response } from 'express';
import { invalidAccountId } from '../accounts/accounts.errors.js';
import { ErrorResponse } from '../common/errors/error-response.js';
import {
  ApiPaginatedResponse,
  PaginationQueryDto,
  type Paginated,
} from '../common/pagination.js';
import { IdempotencyKey } from '../ledger/idempotency-key.decorator.js';
import { IDEMPOTENCY_KEY_RULE } from '../ledger/ledger.errors.js';
import type { AuthenticatedUser } from '../mobile-auth/authenticated-user.js';
import { CurrentUser } from '../mobile-auth/decorators/current-user.decorator.js';
import { MobileRoute } from '../mobile-auth/decorators/mobile-route.decorator.js';
import {
  GoalMovementView,
  MoveBetweenGoalsDto,
} from './dto/goal-movement.dto.js';
import { GoalsService } from './goals.service.js';

const AccountIdPipe = new ParseUUIDPipe({ exceptionFactory: invalidAccountId });

@ApiTags('Mobile - Mes objectifs')
@ApiBearerAuth()
@ApiParam({ name: 'accountId', description: 'Identifiant de mon compte' })
@ApiUnauthorizedResponse({
  description: 'Session absente, expirée ou fermée',
  type: ErrorResponse,
})
@ApiNotFoundResponse({
  description:
    'Compte introuvable parmi les vôtres, ou objectif introuvable sur ce compte',
  type: ErrorResponse,
})
@MobileRoute()
@Controller('me/accounts/:accountId/goal-movements')
export class MyGoalMovementsController {
  constructor(private readonly goals: GoalsService) {}

  /**
   * @description Move money between two goals of one of the user's accounts (the balance does not change)
   * @route POST /api/v1/me/accounts/:accountId/goal-movements
   * @access Mobile session (Bearer), the account's customer only
   * @param accountId one of the user's accounts
   * @header Idempotency-Key a UUID generated by the app for this request
   * @body MoveBetweenGoalsDto (sourceGoalId, targetGoalId, amount)
   * @returns 201 GoalMovementView (200 when the key already recorded this move); 409 INSUFFICIENT_GOAL_BALANCE, GOAL_CLOSED or IDEMPOTENCY_KEY_REUSED
   */
  @Post()
  @ApiOperation({
    summary: 'Déplacer de l’argent entre deux objectifs',
    description:
      'Le solde du compte ne change pas : seule sa répartition entre objectifs change. L’objectif de départ doit contenir le montant ; celui d’arrivée ne doit pas être fermé. Un objectif d’arrivée qui atteint son montant visé passe à `REACHED` et vous êtes prévenu (application et push). Un mouvement enregistré ne peut plus être modifié ni supprimé.',
  })
  @ApiHeader({
    name: 'Idempotency-Key',
    required: true,
    description: IDEMPOTENCY_KEY_RULE,
  })
  @ApiCreatedResponse({
    description: 'Mouvement enregistré',
    type: GoalMovementView,
  })
  @ApiOkResponse({
    description:
      'Demande répétée avec la même clé : ce mouvement était déjà enregistré, il est renvoyé et rien n’est enregistré de nouveau',
    type: GoalMovementView,
  })
  @ApiBadRequestResponse({
    description:
      'Identifiant invalide ; même objectif au départ et à l’arrivée ; montant invalide ; en-tête Idempotency-Key absent ou invalide (`details`)',
    type: ErrorResponse,
  })
  @ApiConflictResponse({
    description:
      'Objectif de départ insuffisant (`INSUFFICIENT_GOAL_BALANCE`) ; objectif d’arrivée fermé (`GOAL_CLOSED`) ; clé déjà utilisée pour un autre mouvement (`IDEMPOTENCY_KEY_REUSED`)',
    type: ErrorResponse,
  })
  async move(
    @CurrentUser() user: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @IdempotencyKey() idempotencyKey: string,
    @Body() body: MoveBetweenGoalsDto,
    @Res({ passthrough: true }) res: Response,
  ): Promise<GoalMovementView> {
    const { movement, replayed } = await this.goals.move(
      user,
      accountId,
      body,
      idempotencyKey,
    );
    res.status(replayed ? HttpStatus.OK : HttpStatus.CREATED);
    return movement;
  }

  /**
   * @description List the account's movements between goals (moves and closings), newest first
   * @route GET /api/v1/me/accounts/:accountId/goal-movements
   * @access Mobile session (Bearer), the account's customer only
   * @param accountId one of the user's accounts
   * @query PaginationQueryDto (page, pageSize)
   * @returns 200 Paginated<GoalMovementView>
   */
  @Get()
  @ApiOperation({
    summary: 'Historique des mouvements entre objectifs',
    description:
      'Les déplacements entre objectifs et les retours dans « Non affecté » à la fermeture d’un objectif, du plus récent au plus ancien.',
  })
  @ApiPaginatedResponse(GoalMovementView, 'Page de mouvements')
  @ApiBadRequestResponse({
    description:
      'Identifiant de compte invalide ; pagination invalide (`details`)',
    type: ErrorResponse,
  })
  movements(
    @CurrentUser() user: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @Query() query: PaginationQueryDto,
  ): Promise<Paginated<GoalMovementView>> {
    return this.goals.movements(user.userId, accountId, query);
  }
}
