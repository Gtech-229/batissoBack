import {
  Body,
  Controller,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Post,
  Res,
} from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiConflictResponse,
  ApiCreatedResponse,
  ApiForbiddenResponse,
  ApiHeader,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import type { Response } from 'express';
import { invalidAccountId } from '../accounts/accounts.errors.js';
import { ErrorResponse } from '../common/errors/error-response.js';
import type { AuthenticatedUser } from '../mobile-auth/authenticated-user.js';
import { CurrentUser } from '../mobile-auth/decorators/current-user.decorator.js';
import { MobileRoute } from '../mobile-auth/decorators/mobile-route.decorator.js';
import type { CurrentStoreContext } from '../store-access/current-store.js';
import { CurrentStore } from '../store-access/decorators/current-store.decorator.js';
import { StoreRoles } from '../store-access/decorators/store-roles.decorator.js';
import { CorrectionsService } from './corrections.service.js';
import { OperationReceipt } from './dto/operation-receipt.js';
import { RecordCorrectionDto } from './dto/record-correction.dto.js';
import { IdempotencyKey } from './idempotency-key.decorator.js';
import { IDEMPOTENCY_KEY_RULE, invalidOperationId } from './ledger.errors.js';

const AccountIdPipe = new ParseUUIDPipe({ exceptionFactory: invalidAccountId });
const OperationIdPipe = new ParseUUIDPipe({
  exceptionFactory: invalidOperationId,
});

@ApiTags('Mobile - Dépôts et historique')
@ApiBearerAuth()
@ApiParam({ name: 'storeId', description: 'Identifiant de la quincaillerie' })
@ApiParam({ name: 'accountId', description: 'Identifiant du compte' })
@ApiParam({
  name: 'operationId',
  description: 'Identifiant du dépôt à corriger',
})
@ApiUnauthorizedResponse({
  description: 'Session absente, expirée ou fermée',
  type: ErrorResponse,
})
@ApiForbiddenResponse({
  description:
    'Membre de la quincaillerie qui n’en est pas le gérant (`STORE_ROLE_REQUIRED`)',
  type: ErrorResponse,
})
@ApiNotFoundResponse({
  description:
    'Quincaillerie introuvable : vous n’en êtes pas membre actif ; compte introuvable dans cette quincaillerie ; ou opération introuvable sur ce compte',
  type: ErrorResponse,
})
@MobileRoute()
@StoreRoles(['MANAGER'])
@Controller(
  'stores/:storeId/accounts/:accountId/operations/:operationId/corrections',
)
export class CorrectionsController {
  constructor(private readonly corrections: CorrectionsService) {}

  /**
   * @description The manager corrects a deposit recorded too high: a CORRECTION operation takes the amount back, linked to the deposit, with a reason
   * @route POST /api/v1/stores/:storeId/accounts/:accountId/operations/:operationId/corrections
   * @access Store manager (mobile session)
   * @param storeId the store
   * @param accountId the account
   * @param operationId the deposit to correct
   * @header Idempotency-Key a UUID generated by the app for this request
   * @body RecordCorrectionDto (amount, reason)
   * @returns 201 OperationReceipt (200 when the key already recorded this correction); 404 account or operation; 409 STORE_CLOSED, OWN_ACCOUNT, NOT_CORRECTABLE, CORRECTION_EXCEEDS_DEPOSIT, INSUFFICIENT_BALANCE or IDEMPOTENCY_KEY_REUSED
   */
  @Post()
  @ApiOperation({
    summary: 'Corriger un dépôt',
    description:
      'Pour un dépôt enregistré en trop (erreur de saisie, argent non remis) : une opération de correction (`CORRECTION`, débit, référence R-…) retire le montant du compte, liée au dépôt, avec le motif, visible par le client. Le dépôt lui-même ne change jamais. Au plus ce qui reste à corriger sur ce dépôt. Le montant est pris dans l’objectif du dépôt, puis dans « Non affecté » ; si l’objectif est fermé, dans « Non affecté ». Seul le gérant corrige, jamais sur son propre compte ; pas dans une quincaillerie fermée. Le client est prévenu (application, push et SMS).',
  })
  @ApiHeader({
    name: 'Idempotency-Key',
    required: true,
    description: IDEMPOTENCY_KEY_RULE,
  })
  @ApiCreatedResponse({
    description: 'Correction enregistrée',
    type: OperationReceipt,
  })
  @ApiOkResponse({
    description:
      'Demande répétée avec la même clé : cette correction était déjà enregistrée, son reçu est renvoyé et rien n’est enregistré de nouveau',
    type: OperationReceipt,
  })
  @ApiBadRequestResponse({
    description:
      'Identifiant de quincaillerie, de compte ou d’opération invalide ; montant ou motif invalide ; en-tête Idempotency-Key absent ou invalide (`details`)',
    type: ErrorResponse,
  })
  @ApiConflictResponse({
    description:
      'Quincaillerie fermée (`STORE_CLOSED`) ; votre propre compte (`OWN_ACCOUNT`) ; l’opération n’est pas un dépôt (`NOT_CORRECTABLE`) ; montant au-delà de ce qui reste à corriger (`CORRECTION_EXCEEDS_DEPOSIT`) ; l’objectif du dépôt et « Non affecté » ne contiennent pas assez (`INSUFFICIENT_BALANCE`) ; clé déjà utilisée pour une autre opération (`IDEMPOTENCY_KEY_REUSED`)',
    type: ErrorResponse,
  })
  async correct(
    @CurrentStore() store: CurrentStoreContext,
    @CurrentUser() actor: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @Param('operationId', OperationIdPipe) operationId: string,
    @IdempotencyKey() idempotencyKey: string,
    @Body() body: RecordCorrectionDto,
    @Res({ passthrough: true }) res: Response,
  ): Promise<OperationReceipt> {
    const { receipt, replayed } = await this.corrections.correct(
      store,
      actor,
      accountId,
      operationId,
      body,
      idempotencyKey,
    );
    res.status(replayed ? HttpStatus.OK : HttpStatus.CREATED);
    return receipt;
  }
}
