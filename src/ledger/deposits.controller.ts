import {
  Body,
  Controller,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Post,
  Res,
} from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiConflictResponse,
  ApiCreatedResponse,
  ApiForbiddenResponse,
  ApiHeader,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import { invalidAccountId } from '../accounts/accounts.errors.js';
import type { Response } from 'express';
import { ErrorResponse } from '../common/errors/error-response.js';
import type { AuthenticatedUser } from '../mobile-auth/authenticated-user.js';
import { CurrentUser } from '../mobile-auth/decorators/current-user.decorator.js';
import { MobileRoute } from '../mobile-auth/decorators/mobile-route.decorator.js';
import type { CurrentStoreContext } from '../store-access/current-store.js';
import { CurrentStore } from '../store-access/decorators/current-store.decorator.js';
import { StoreRoles } from '../store-access/decorators/store-roles.decorator.js';
import { OperationReceipt } from './dto/operation-receipt.js';
import { RecordDepositDto } from './dto/record-deposit.dto.js';
import { IdempotencyKey } from './idempotency-key.decorator.js';
import { IDEMPOTENCY_KEY_RULE } from './ledger.errors.js';
import { LedgerService } from './ledger.service.js';

const AccountIdPipe = new ParseUUIDPipe({ exceptionFactory: invalidAccountId });

@ApiTags('Mobile - Dépôts et historique')
@ApiBearerAuth()
@ApiParam({ name: 'storeId', description: 'Identifiant de la quincaillerie' })
@ApiParam({ name: 'accountId', description: 'Identifiant du compte' })
@ApiUnauthorizedResponse({
  description: 'Session absente, expirée ou fermée',
  type: ErrorResponse,
})
@ApiForbiddenResponse({
  description:
    'Membre de la quincaillerie sans le rôle de vendeur ou de gérant (`STORE_ROLE_REQUIRED`)',
  type: ErrorResponse,
})
@ApiNotFoundResponse({
  description:
    'Quincaillerie introuvable : vous n’en êtes pas membre actif, ou compte introuvable dans cette quincaillerie',
  type: ErrorResponse,
})
@MobileRoute()
@StoreRoles(['MANAGER', 'SELLER'])
@Controller('stores/:storeId/accounts/:accountId/deposits')
export class DepositsController {
  constructor(private readonly ledger: LedgerService) {}

  /**
   * @description Record cash handed over by the customer at the counter
   * @route POST /api/v1/stores/:storeId/accounts/:accountId/deposits
   * @access Store seller or manager (mobile session)
   * @param storeId the store
   * @param accountId the account
   * @header Idempotency-Key a UUID generated by the app for this request
   * @body RecordDepositDto (amount)
   * @returns 201 OperationReceipt (200 when the key already recorded this deposit); 409 STORE_NOT_VERIFIED, OWN_ACCOUNT, BELOW_MIN_DEPOSIT, MAX_BALANCE_EXCEEDED or IDEMPOTENCY_KEY_REUSED
   */
  @Post()
  @ApiOperation({
    summary: 'Enregistrer un dépôt en espèces',
    description:
      'Ajoute le montant au solde du compte (objectif « Non affecté ») et renvoie le reçu, avec le solde avant et après. Le montant doit atteindre le dépôt minimum de la quincaillerie, et le solde ne doit pas dépasser son solde maximal. Un membre de l’équipe ne peut pas enregistrer de dépôt sur son propre compte. Seulement pour une quincaillerie vérifiée. Une opération enregistrée ne peut plus être modifiée ni supprimée.',
  })
  @ApiHeader({
    name: 'Idempotency-Key',
    required: true,
    description: IDEMPOTENCY_KEY_RULE,
  })
  @ApiCreatedResponse({
    description: 'Dépôt enregistré',
    type: OperationReceipt,
  })
  @ApiOkResponse({
    description:
      'Demande répétée avec la même clé : ce dépôt était déjà enregistré, son reçu est renvoyé et rien n’est enregistré de nouveau',
    type: OperationReceipt,
  })
  @ApiBadRequestResponse({
    description:
      'Identifiant de quincaillerie ou de compte invalide ; montant invalide ; en-tête Idempotency-Key absent ou invalide (`details`)',
    type: ErrorResponse,
  })
  @ApiConflictResponse({
    description:
      'Quincaillerie non vérifiée (`STORE_NOT_VERIFIED`) ; votre propre compte (`OWN_ACCOUNT`) ; montant sous le dépôt minimum (`BELOW_MIN_DEPOSIT`) ; solde maximal dépassé (`MAX_BALANCE_EXCEEDED`) ; clé déjà utilisée pour une autre opération (`IDEMPOTENCY_KEY_REUSED`)',
    type: ErrorResponse,
  })
  async deposit(
    @CurrentStore() store: CurrentStoreContext,
    @CurrentUser() actor: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @IdempotencyKey() idempotencyKey: string,
    @Body() body: RecordDepositDto,
    @Res({ passthrough: true }) res: Response,
  ): Promise<OperationReceipt> {
    const { receipt, replayed } = await this.ledger.deposit(
      store,
      actor,
      accountId,
      body,
      idempotencyKey,
    );
    res.status(replayed ? HttpStatus.OK : HttpStatus.CREATED);
    return receipt;
  }
}
