import {
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Post,
  Query,
  Res,
} from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiConflictResponse,
  ApiCreatedResponse,
  ApiForbiddenResponse,
  ApiHeader,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import { invalidAccountId } from '../accounts/accounts.errors.js';
import type { Response } from 'express';
import { ErrorResponse } from '../common/errors/error-response.js';
import { IdempotencyKey } from '../ledger/idempotency-key.decorator.js';
import { IDEMPOTENCY_KEY_RULE } from '../ledger/ledger.errors.js';
import { ApiPaginatedResponse, type Paginated } from '../common/pagination.js';
import type { AuthenticatedUser } from '../mobile-auth/authenticated-user.js';
import { CurrentUser } from '../mobile-auth/decorators/current-user.decorator.js';
import { MobileRoute } from '../mobile-auth/decorators/mobile-route.decorator.js';
import { ListMyOrdersQueryDto } from './dto/list-orders.dto.js';
import { ConfirmByPinDto } from './dto/order-confirmation.dto.js';
import {
  CancellationRequestDto,
  CustomerRefusalDto,
} from './dto/order-decisions.dto.js';
import { MyOrderView } from './dto/my-order-view.js';
import { invalidOrderId } from './orders.errors.js';
import { OrdersService } from './orders.service.js';

const AccountIdPipe = new ParseUUIDPipe({ exceptionFactory: invalidAccountId });
const OrderIdPipe = new ParseUUIDPipe({ exceptionFactory: invalidOrderId });

@ApiTags('Mobile - Mes bons de sortie')
@ApiBearerAuth()
@ApiParam({ name: 'accountId', description: 'Identifiant de mon compte' })
@ApiUnauthorizedResponse({
  description: 'Session absente, expirée ou fermée',
  type: ErrorResponse,
})
@ApiNotFoundResponse({
  description:
    'Compte introuvable parmi les vôtres, ou bon introuvable sur ce compte',
  type: ErrorResponse,
})
@MobileRoute()
@Controller('me/accounts/:accountId/orders')
export class MyOrdersController {
  constructor(private readonly orders: OrdersService) {}

  /**
   * @description List the material orders of one of the user's accounts, newest first
   * @route GET /api/v1/me/accounts/:accountId/orders
   * @access Mobile session (Bearer), the account's customer only
   * @param accountId one of the user's accounts
   * @query ListMyOrdersQueryDto (page, pageSize, status?)
   * @returns 200 Paginated<MyOrderView>
   */
  @Get()
  @ApiOperation({
    summary: 'Mes bons de sortie',
    description:
      'Les bons préparés sur ce compte, du plus récent au plus ancien, paginés, avec leurs lignes et leur état.',
  })
  @ApiPaginatedResponse(MyOrderView, 'Mes bons de sortie')
  @ApiBadRequestResponse({
    description:
      'Identifiant de compte invalide ; filtre ou pagination invalide (`details`)',
    type: ErrorResponse,
  })
  list(
    @CurrentUser() user: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @Query() query: ListMyOrdersQueryDto,
  ): Promise<Paginated<MyOrderView>> {
    return this.orders.listMine(user.userId, accountId, query);
  }

  /**
   * @description One material order of one of the user's accounts
   * @route GET /api/v1/me/accounts/:accountId/orders/:orderId
   * @access Mobile session (Bearer), the account's customer only
   * @param accountId one of the user's accounts
   * @param orderId the order
   * @returns 200 MyOrderView
   */
  @Get(':orderId')
  @ApiOperation({ summary: 'Détail d’un de mes bons de sortie' })
  @ApiParam({ name: 'orderId', description: 'Identifiant du bon' })
  @ApiOkResponse({ description: 'Bon', type: MyOrderView })
  @ApiBadRequestResponse({
    description: 'Identifiant de compte ou de bon invalide',
    type: ErrorResponse,
  })
  detail(
    @CurrentUser() user: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @Param('orderId', OrderIdPipe) orderId: string,
  ): Promise<MyOrderView> {
    return this.orders.detailMine(user.userId, accountId, orderId);
  }

  /**
   * @description Confirm an order with the PIN: the account is debited, from the order's goal then Unassigned
   * @route POST /api/v1/me/accounts/:accountId/orders/:orderId/confirm
   * @access Mobile session (Bearer), the account's customer only
   * @param accountId one of the user's accounts
   * @param orderId the order, awaiting the customer
   * @header Idempotency-Key a UUID generated by the app for this request
   * @body ConfirmByPinDto (pin)
   * @returns 201 MyOrderView (200 when the key already confirmed this order); 400 INVALID_PIN; 403 PIN_LOCKED; 409 ORDER_STATUS, STORE_CLOSED, GOAL_CLOSED, INSUFFICIENT_BALANCE or IDEMPOTENCY_KEY_REUSED
   */
  @Post(':orderId/confirm')
  @ApiOperation({
    summary: 'Confirmer un bon avec mon code PIN',
    description:
      'Seulement pour un bon en attente de votre confirmation (`AWAITING_CUSTOMER`). Le montant du bon est débité de votre compte : de l’objectif du bon, puis de « Non affecté » pour le reste. Le solde est vérifié à nouveau à ce moment. Un code PIN faux compte dans le blocage de la connexion. Le bon passe à `CONFIRMED` avec la référence du débit (`debitReference`). Une opération enregistrée ne peut plus être modifiée.',
  })
  @ApiParam({ name: 'orderId', description: 'Identifiant du bon' })
  @ApiHeader({
    name: 'Idempotency-Key',
    required: true,
    description: IDEMPOTENCY_KEY_RULE,
  })
  @ApiCreatedResponse({
    description: 'Bon confirmé et débité',
    type: MyOrderView,
  })
  @ApiOkResponse({
    description:
      'Cette clé a déjà confirmé ce bon : le bon, rien n’est débité à nouveau',
    type: MyOrderView,
  })
  @ApiBadRequestResponse({
    description:
      'Identifiant invalide ; code PIN faux (`INVALID_PIN`) ou mal formé ; en-tête Idempotency-Key absent ou invalide (`details`)',
    type: ErrorResponse,
  })
  @ApiForbiddenResponse({
    description: 'Trop de codes PIN faux : réessayez plus tard (`PIN_LOCKED`)',
    type: ErrorResponse,
  })
  @ApiConflictResponse({
    description:
      'Le bon n’attend pas votre confirmation (`ORDER_STATUS`) ; quincaillerie fermée (`STORE_CLOSED`) ; objectif fermé (`GOAL_CLOSED`) ; solde insuffisant (`INSUFFICIENT_BALANCE`) ; clé déjà utilisée pour une autre opération (`IDEMPOTENCY_KEY_REUSED`)',
    type: ErrorResponse,
  })
  async confirm(
    @CurrentUser() user: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @Param('orderId', OrderIdPipe) orderId: string,
    @IdempotencyKey() idempotencyKey: string,
    @Body() body: ConfirmByPinDto,
    @Res({ passthrough: true }) res: Response,
  ): Promise<MyOrderView> {
    const { order, replayed } = await this.orders.confirmMine(
      user,
      accountId,
      orderId,
      body.pin,
      idempotencyKey,
    );
    res.status(replayed ? HttpStatus.OK : HttpStatus.CREATED);
    return order;
  }

  /**
   * @description Refuse an order awaiting the customer: nothing is debited, the manager is alerted
   * @route POST /api/v1/me/accounts/:accountId/orders/:orderId/refuse
   * @access Mobile session (Bearer), the account's customer only
   * @param accountId one of the user's accounts
   * @param orderId the order, awaiting the customer
   * @body CustomerRefusalDto (reason?)
   * @returns 200 MyOrderView; 409 ORDER_STATUS or STORE_CLOSED
   */
  @Post(':orderId/refuse')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: 'Refuser un bon',
    description:
      'Seulement pour un bon en attente de votre confirmation : il passe à `REFUSED_BY_CUSTOMER`, rien n’est débité, et le gérant de la quincaillerie est prévenu (avec votre motif, facultatif).',
  })
  @ApiParam({ name: 'orderId', description: 'Identifiant du bon' })
  @ApiOkResponse({ description: 'Bon refusé', type: MyOrderView })
  @ApiBadRequestResponse({
    description:
      'Identifiant de compte ou de bon invalide ; motif invalide (`details`)',
    type: ErrorResponse,
  })
  @ApiConflictResponse({
    description:
      'Le bon n’attend pas votre confirmation (`ORDER_STATUS`) ; quincaillerie fermée (`STORE_CLOSED`)',
    type: ErrorResponse,
  })
  refuse(
    @CurrentUser() user: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @Param('orderId', OrderIdPipe) orderId: string,
    @Body() body: CustomerRefusalDto,
  ): Promise<MyOrderView> {
    return this.orders.refuseMine(user.userId, accountId, orderId, body);
  }

  /**
   * @description Ask to cancel a paid order still undelivered after the store's delivery delay: the manager is alerted
   * @route POST /api/v1/me/accounts/:accountId/orders/:orderId/cancellation-request
   * @access Mobile session (Bearer), the account's customer only
   * @param accountId one of the user's accounts
   * @param orderId the order, confirmed (paid) and not delivered
   * @body CancellationRequestDto (reason?)
   * @returns 200 MyOrderView; 409 ORDER_STATUS, CANCELLATION_ALREADY_REQUESTED or DELIVERY_DELAY_NOT_REACHED
   */
  @Post(':orderId/cancellation-request')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: 'Demander l’annulation d’un bon payé non livré',
    description:
      'Pour un bon confirmé (déjà débité) qui n’est toujours pas livré après le délai de livraison de la quincaillerie (30 jours par défaut, comptés depuis votre confirmation) : la demande est enregistrée (date et motif facultatif) et le gérant est prévenu. Le bon reste `CONFIRMED` : le gérant le livre, ou l’annule et vous rembourse sur votre compte. Une seule demande par bon.',
  })
  @ApiParam({ name: 'orderId', description: 'Identifiant du bon' })
  @ApiOkResponse({ description: 'Demande enregistrée', type: MyOrderView })
  @ApiBadRequestResponse({
    description:
      'Identifiant de compte ou de bon invalide ; motif invalide (`details`)',
    type: ErrorResponse,
  })
  @ApiConflictResponse({
    description:
      'Le bon n’est pas confirmé ou il est déjà livré ou annulé (`ORDER_STATUS`) ; demande déjà faite (`CANCELLATION_ALREADY_REQUESTED`) ; délai de livraison pas encore écoulé, le message donne la date (`DELIVERY_DELAY_NOT_REACHED`)',
    type: ErrorResponse,
  })
  requestCancellation(
    @CurrentUser() user: AuthenticatedUser,
    @Param('accountId', AccountIdPipe) accountId: string,
    @Param('orderId', OrderIdPipe) orderId: string,
    @Body() body: CancellationRequestDto,
  ): Promise<MyOrderView> {
    return this.orders.requestCancellation(
      user.userId,
      accountId,
      orderId,
      body,
    );
  }
}
